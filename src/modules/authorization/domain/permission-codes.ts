export type PermissionCode = (typeof PERMISSION_CODES)[keyof typeof PERMISSION_CODES];

export const PERMISSION_CODE_LIST: readonly PermissionCode[] = Object.freeze(
  Object.values(PERMISSION_CODES),
);

const PERMISSION_CODE_SET: ReadonlySet<string> = new Set<string>(PERMISSION_CODE_LIST);

export function isPermissionCode(value: unknown): value is PermissionCode {
  return typeof value === 'string' && PERMISSION_CODE_SET.has(value);
}

